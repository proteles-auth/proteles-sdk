#!/usr/bin/env node
// Generates the Management SDK's enum unions from spec/openapi.json.
//
// The types were hand-written, and hand-written copies of a list drift. This
// exists because they already had: `MfaPolicy` read `"optional" | "required"`
// for as long as the server had a third policy, and `provider` is declared two
// different ways in one types.ts — `string` on one interface and a full union
// on another, for the same four values.
//
// Scope is deliberately **enums only**, not whole interfaces. The SDK's public
// surface is camelCase and the wire is snake_case, so generating interfaces
// would either replace a deliberate API or add a parallel one nobody asked for.
// The enums are the part that is identical on both sides and the part that
// actually goes stale, because a new value is a one-line server change nobody
// thinks to mirror.
//
// Closed unions, not open. An open union (`| (string & {})`) never fails, which
// defeats generating it — the whole point is that a value added to the spec
// shows up here. Where the SDK deliberately wants openness on a response field
// it composes: `export type X = GeneratedX | (string & {})`, so the generated
// half still cannot drift.
//
//   node tools/generate-management-enums.mjs           # write the file
//   node tools/generate-management-enums.mjs --check   # fail if it is stale
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SPEC = path.join(ROOT, "spec/openapi.json");
const OUT = path.join(ROOT, "packages/management/src/generated/enums.ts");

/** `mfa_policy` becomes `MfaPolicy`, `client_type` becomes `ClientType`. */
const pascal = (snake) =>
  snake
    .split("_")
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");

/**
 * Every distinct `(field, value-set)` the spec declares.
 *
 * Grouped by the pair, not by the field alone. The first draft keyed on the
 * field name, reasoning that one field means one thing — and the spec disproved
 * it immediately: `status` is `active|suspended` on a tenant, `pending|delivered`
 * on a webhook delivery and `exhausted|delivered` on a replay request, and
 * `error` carries a different code set for each API area. Merging those would
 * have produced a type wrong for every user of it; taking the union would have
 * been wrong for all three at once.
 *
 * So a field with one value-set gets the obvious name, and a field with several
 * gets one type per set, qualified by the schema that declares it. The
 * qualified names are ugly. They are also generated, so nobody types them, and
 * ambiguity here would be a client that compiles against the wrong set of
 * values.
 */
export function collect(spec) {
  const groups = new Map();
  const schemas = (spec.components && spec.components.schemas) || {};
  for (const [schemaName, schema] of Object.entries(schemas)) {
    for (const [field, prop] of Object.entries((schema && schema.properties) || {})) {
      if (!prop || !Array.isArray(prop.enum)) continue;
      const nullable = prop.enum.includes(null);
      const values = prop.enum.filter((v) => v !== null).map(String).sort();
      const key = `${field}\u0000${values.join("\u0001")}`;
      const seen = groups.get(key);
      if (seen) {
        seen.nullable = seen.nullable || nullable;
        seen.from.push(schemaName);
      } else {
        groups.set(key, { field, values, nullable, from: [schemaName] });
      }
    }
  }

  // How many distinct sets each field has; one means the plain name is safe.
  const setsPerField = new Map();
  for (const g of groups.values()) {
    setsPerField.set(g.field, (setsPerField.get(g.field) || 0) + 1);
  }

  return [...groups.values()]
    .map((g) => {
      const from = [...g.from].sort();
      const name =
        setsPerField.get(g.field) === 1 ? pascal(g.field) : `${from[0]}${pascal(g.field)}`;
      return { ...g, from, name };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

export function render(spec) {
  const out = [
    "// GENERATED by tools/generate-management-enums.mjs - do not edit.",
    "//",
    "// Every enum the Management API declares, read from spec/openapi.json.",
    "// Run `node tools/generate-management-enums.mjs` after changing the spec;",
    "// CI fails if this file and the spec disagree.",
    "",
  ];
  for (const { field, values, nullable, from, name } of collect(spec)) {
    const union =
      values.map((v) => JSON.stringify(v)).join(" | ") + (nullable ? " | null" : "");
    out.push(`/** \`${field}\` - declared by ${from.join(", ")}. */`);
    out.push(`export type ${name} = ${union};`);
    out.push("");
  }
  return out.join("\n");
}

if (process.argv.includes("--self-test")) {
  const cases = [];
  const check = (name, fn) => {
    try {
      fn();
      cases.push([true, name]);
    } catch (e) {
      cases.push([false, `${name}: ${e.message}`]);
    }
  };
  const spec = (schemas) => ({ components: { schemas } });
  const assert = (cond, msg) => {
    if (!cond) throw new Error(msg);
  };

  check("one field, one union", () => {
    const out = render(spec({ A: { properties: { mfa_policy: { enum: ["b", "a"] } } } }));
    assert(out.includes('export type MfaPolicy = "a" | "b";'), out);
  });
  check("the same field in two schemas is one type, not two", () => {
    const out = render(
      spec({
        A: { properties: { mfa_policy: { enum: ["a"] } } },
        B: { properties: { mfa_policy: { enum: ["a"] } } },
      }),
    );
    assert(out.split("export type MfaPolicy").length === 2, "emitted more than once");
    assert(out.includes("declared by A, B"), out);
  });
  check("a null member becomes a nullable union", () => {
    const out = render(spec({ A: { properties: { reason: { enum: ["x", null] } } } }));
    assert(out.includes('export type Reason = "x" | null;'), out);
  });
  check("one field with two value sets becomes two qualified types", () => {
    // The case that disproved keying on the field name alone. Neither may win
    // and they must not be merged: a client typed against the union would
    // compile with a value the endpoint refuses.
    const out = render(
      spec({
        Alpha: { properties: { status: { enum: ["a"] } } },
        Beta: { properties: { status: { enum: ["b"] } } },
      }),
    );
    assert(out.includes('export type AlphaStatus = "a";'), out);
    assert(out.includes('export type BetaStatus = "b";'), out);
    assert(!/export type Status =/.test(out), "the ambiguous plain name must not be emitted");
  });
  check("a field with one value set keeps the plain name even across schemas", () => {
    const out = render(
      spec({
        Alpha: { properties: { kind: { enum: ["x"] } } },
        Beta: { properties: { kind: { enum: ["x"] } } },
      }),
    );
    assert(out.includes('export type Kind = "x";'), out);
    assert(out.split("export type Kind").length === 2, "emitted more than once");
  });
  check("a property with no enum is ignored", () => {
    const out = render(spec({ A: { properties: { slug: { type: "string" } } } }));
    assert(!out.includes("export type Slug"), out);
  });

  for (const [ok, name] of cases) console.log(`  ${ok ? "[32m✓[0m" : "[31m✗[0m"} ${name}`);
  const bad = cases.filter(([ok]) => !ok).length;
  console.log(bad === 0 ? "\nthe generator behaves" : `\n${bad} case(s) wrong`);
  process.exit(bad === 0 ? 0 : 1);
}

const spec = JSON.parse(readFileSync(SPEC, "utf8"));
const rendered = render(spec);

if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(OUT, "utf8");
  } catch {
    console.error(`✗ ${path.relative(ROOT, OUT)} is missing - run the generator and commit it.`);
    process.exit(1);
  }
  if (committed !== rendered) {
    console.error(
      `✗ ${path.relative(ROOT, OUT)} does not match spec/openapi.json.\n` +
        "  Run: node tools/generate-management-enums.mjs\n" +
        "  A spec change that never reached the SDK is a client that types a value the\n" +
        "  server refuses, or omits one the server returns - and neither shows up until\n" +
        "  somebody's build breaks.",
    );
    process.exit(1);
  }
  console.log("✓ the generated enums match the spec");
  process.exit(0);
}

writeFileSync(OUT, rendered);
console.log(`wrote ${path.relative(ROOT, OUT)}`);
