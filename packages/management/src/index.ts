// It used to be a hand-picked list under the heading "everything a public
// method mentions", and it went wrong the same way twice. First `Usage`,
// `UsagePoint`, `GetUsageOptions` and `ManagementScope` were missing, so
// `getUsage` returned a type the caller could not name. Then `ClientType`,
// `Provider`, `Severity` and `TokenEndpointAuthMethod` — which `types.ts`
// aliases out of `generated/` under the comment "so callers can name them
// without reaching into `generated/`", and which this file then did not
// re-export, so there was no reach to be spared.
//
// A curated list of what to export has to be re-curated on every change, and
// nothing checks it. Exporting what is declared cannot fall behind: `types.ts`
